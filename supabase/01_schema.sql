-- ---------- Profil pengguna (terhubung ke akun Supabase Auth) ----------
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  username    text unique not null,
  nama        text not null,
  role        text not null default 'pekerja' check (role in ('admin','pekerja')),
  aktif       boolean not null default false,   -- akun baru menunggu persetujuan admin
  created_at  timestamptz not null default now()
);

-- Akun pertama otomatis jadi admin aktif; akun berikutnya menunggu diaktifkan admin.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  first_user boolean;
  uname text := lower(split_part(new.email, '@', 1));
begin
  select not exists (select 1 from public.profiles) into first_user;
  insert into public.profiles (id, username, nama, role, aktif)
  values (new.id, uname,
          coalesce(nullif(new.raw_user_meta_data->>'nama', ''), uname),
          case when first_user then 'admin' else 'pekerja' end,
          first_user);
  return new;
end $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.is_staff()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and aktif);
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.profiles where id = auth.uid() and aktif and role = 'admin');
$$;

-- ---------- Produk ----------
create table if not exists public.products (
  sku      integer primary key,
  kode     text,
  jenis    text not null,
  urat     text,
  panjang  integer,
  kain     text not null default 'N' check (kain in ('Y','N')),   -- Y = kain, N = polos
  aktif    boolean not null default true
);

-- ---------- Transaksi barang masuk / keluar ----------
create table if not exists public.transactions (
  id          bigint generated by default as identity primary key,
  tipe        text not null check (tipe in ('masuk','keluar')),
  tanggal     date not null default current_date,
  keterangan  text not null default '',
  sku         integer not null references public.products(sku),
  qty         integer not null check (qty > 0),
  catatan     text not null default '',
  dihapus     boolean not null default false,
  alasan      text,                                   -- alasan hapus / pulihkan terakhir
  created_by  uuid references public.profiles(id) default auth.uid(),
  created_at  timestamptz not null default now(),
  updated_by  uuid references public.profiles(id),
  updated_at  timestamptz
);
create index if not exists idx_tx_sku on public.transactions(sku);
create index if not exists idx_tx_tanggal on public.transactions(tanggal desc);

-- ---------- Riwayat pelacakan (otomatis lewat trigger, tidak bisa diubah) ----------
create table if not exists public.history (
  id              bigint generated by default as identity primary key,
  transaction_id  bigint not null references public.transactions(id) on delete cascade,
  aksi            text not null,              -- dibuat | impor | diubah | dihapus | dipulihkan
  perubahan       jsonb,                      -- {"qty": [lama, baru], ...}
  alasan          text,
  user_id         uuid references public.profiles(id),
  waktu           timestamptz not null default now()
);
create index if not exists idx_hist_tx on public.history(transaction_id);
create index if not exists idx_hist_waktu on public.history(waktu desc);

-- Isi pengubah/waktu ubah otomatis, dan kunci kolom pembuat
create or replace function public.tx_before_update()
returns trigger language plpgsql as $$
begin
  new.created_by := old.created_by;
  new.created_at := old.created_at;
  new.updated_by := auth.uid();
  new.updated_at := now();
  -- Edit data atau hapus oleh pengguna: alasan wajib ditulis di kolom catatan (min. 10 karakter)
  if auth.uid() is not null and (
       (new.dihapus and not old.dihapus)
       or (new.tipe, new.tanggal, new.keterangan, new.sku, new.qty)
          is distinct from (old.tipe, old.tanggal, old.keterangan, old.sku, old.qty)) then
    if length(btrim(coalesce(new.catatan, ''))) < 10 or new.catatan is not distinct from old.catatan then
      raise exception 'Alasan wajib ditulis di kolom catatan (minimal 10 karakter).'
        using errcode = 'check_violation';
    end if;
  end if;
  if new.dihapus and not old.dihapus then
    new.alasan := new.catatan;
  end if;
  return new;
end $$;

drop trigger if exists tx_before_update on public.transactions;
create trigger tx_before_update before update on public.transactions
  for each row execute function public.tx_before_update();

create or replace function public.tx_log()
returns trigger language plpgsql security definer set search_path = public as $$
declare
  diff jsonb := '{}'::jsonb;
  col  text;
begin
  if tg_op = 'INSERT' then
    insert into history (transaction_id, aksi, perubahan, user_id)
    values (new.id, case when auth.uid() is null then 'impor' else 'dibuat' end,
            jsonb_build_object('tipe', new.tipe, 'qty', new.qty, 'sku', new.sku), auth.uid());
    return new;
  end if;

  if new.dihapus is distinct from old.dihapus then
    insert into history (transaction_id, aksi, alasan, user_id)
    values (new.id, case when new.dihapus then 'dihapus' else 'dipulihkan' end, new.alasan, auth.uid());
  end if;

  foreach col in array array['tipe','tanggal','keterangan','sku','qty','catatan'] loop
    if (to_jsonb(old) -> col) is distinct from (to_jsonb(new) -> col) then
      diff := diff || jsonb_build_object(col, jsonb_build_array(to_jsonb(old) -> col, to_jsonb(new) -> col));
    end if;
  end loop;
  if new.dihapus is distinct from old.dihapus then
    diff := diff - 'catatan';   -- alasan hapus sudah tercatat di baris 'dihapus'
  end if;
  if diff <> '{}'::jsonb then
    insert into history (transaction_id, aksi, perubahan, alasan, user_id)
    values (new.id, 'diubah', diff, case when diff ? 'catatan' then new.catatan end, auth.uid());
  end if;
  return new;
end $$;

drop trigger if exists tx_log on public.transactions;
create trigger tx_log after insert or update on public.transactions
  for each row execute function public.tx_log();

-- ---------- Tampilan stok (boleh dilihat publik tanpa login) ----------
-- View berjalan dengan hak pemilik, jadi publik hanya melihat JUMLAH stok,
-- bukan nama pelanggan / detail transaksi.
create or replace view public.stok as
select p.sku, p.kode, p.jenis, p.urat, p.panjang, p.kain, p.aktif,
       coalesce(sum(t.qty) filter (where t.tipe = 'masuk'), 0)::int  as masuk,
       coalesce(sum(t.qty) filter (where t.tipe = 'keluar'), 0)::int as keluar,
       (coalesce(sum(t.qty) filter (where t.tipe = 'masuk'), 0)
        - coalesce(sum(t.qty) filter (where t.tipe = 'keluar'), 0))::int as stok,
       max(t.tanggal) as terakhir
from public.products p
left join public.transactions t on t.sku = p.sku and not t.dihapus
group by p.sku;

-- ---------- Keamanan (Row Level Security) ----------
alter table public.profiles     enable row level security;
alter table public.products     enable row level security;
alter table public.transactions enable row level security;
alter table public.history      enable row level security;

-- profiles
drop policy if exists "profil dibaca staf atau diri sendiri" on public.profiles;
create policy "profil dibaca staf atau diri sendiri" on public.profiles
  for select to authenticated using (public.is_staff() or id = auth.uid());
drop policy if exists "admin ubah profil" on public.profiles;
create policy "admin ubah profil" on public.profiles
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

-- products: semua orang boleh lihat, admin yang mengelola
drop policy if exists "produk publik" on public.products;
create policy "produk publik" on public.products for select to anon, authenticated using (true);
drop policy if exists "admin tambah produk" on public.products;
create policy "admin tambah produk" on public.products for insert to authenticated with check (public.is_admin());
drop policy if exists "admin ubah produk" on public.products;
create policy "admin ubah produk" on public.products for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

-- transactions: hanya staf aktif; tidak ada hapus permanen (pakai kolom dihapus)
drop policy if exists "staf lihat transaksi" on public.transactions;
create policy "staf lihat transaksi" on public.transactions for select to authenticated using (public.is_staff());
drop policy if exists "staf tambah transaksi" on public.transactions;
create policy "staf tambah transaksi" on public.transactions for insert to authenticated
  with check (public.is_staff() and created_by = auth.uid());
drop policy if exists "staf ubah transaksi" on public.transactions;
create policy "staf ubah transaksi" on public.transactions for update to authenticated
  using (public.is_staff()) with check (public.is_staff());

-- history: hanya dibaca staf; ditulis oleh trigger
drop policy if exists "staf lihat riwayat" on public.history;
create policy "staf lihat riwayat" on public.history for select to authenticated using (public.is_staff());

-- Hak akses dasar
revoke all on public.profiles, public.products, public.transactions, public.history from anon;
grant select on public.products to anon;
grant select on public.stok to anon, authenticated;
grant select, update on public.profiles to authenticated;
grant select, insert, update on public.products to authenticated;
grant select, insert, update on public.transactions to authenticated;
grant select on public.history to authenticated;
revoke delete on public.transactions, public.history, public.products from authenticated;
revoke insert, update on public.history from authenticated;

-- Muat ulang cache API Supabase supaya tabel baru langsung terlihat
notify pgrst, 'reload schema';
